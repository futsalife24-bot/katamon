#!/usr/bin/env python3
"""Pack approved transparent frames into the legacy game's five-clip format.

Run after Content Studio's generate-game-content step. The catalog is generated
output; this command deterministically reapplies only legacy motion bindings.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parents[1]
OUTPUT_SIZE = 256
CLIPS = {"forward": ("move-forward", 8, 12, True), "backward": ("move-backward", 8, 10, True),
         "fire": ("fire", 8, 12, False), "hit": ("hit", 12, 12, False), "land": ("land", 8, 10, False)}
IDENTITIES = [("kyoryu", "dirano"), ("medama", "eyebolt"), ("iwa", "gorocca"),
              ("tori", "fenice"), ("barugerukan", "barugerukan"), ("nisenmono", "obelisk"),
              ("burumutan", "bloom-tan"), ("sumoeru", "sumoeru"), ("doRednote", "dread-arrow"),
              ("hamulton", "hamulton"), ("mocchario", "mocchario"), ("mecha", "chrome-gear"),
              ("akuma", "rubidevi"), ("jinba", "astauros"), ("kishi", "paladier"),
              ("neko", "nyan-tank"), ("shinigami", "yomigama"), ("coolKai", "cool-kai")]


def source_dir(asset, action, selected, others, pilot, generated):
    if asset in ("dirano", "eyebolt"):
        value = selected[f"{asset}-{action}"]
        path = others / value
    elif asset == "nyan-tank":
        versions = {"forward": 1, "backward": 2, "fire": 2, "hit": 1, "land": 2}
        path = pilot / f"{action}-frames-v{versions[action]}"
    else:
        selection_file = generated.parent / "selected-folders.json"
        choices = json.loads(selection_file.read_text(encoding="utf-8")) if selection_file.exists() else {}
        chosen = choices.get(f"{asset}-{action}")
        if not chosen:
            raise FileNotFoundError(f"検査合格した入力の選択がありません: {asset}-{action}")
        path = generated.parent / chosen
    if not path.is_dir():
        raise FileNotFoundError(f"入力フォルダーがありません: {path}")
    return path


def bounds(image):
    alpha = image.getchannel("A").point(lambda x: 255 if x > 4 else 0)
    box = alpha.getbbox()
    if box is None:
        raise ValueError("空のフレームがあります")
    return {"x": box[0], "y": box[1], "width": box[2] - box[0], "height": box[3] - box[1]}


def parameters(count, fps):
    return {"frameCount": count, "fps": fps, "durationMs": round(count * 1000 / fps),
            "moveX": 0, "moveY": 0, "scaleAmount": 0, "squashAmount": 0,
            "rotationDegrees": 0, "idlePause": 0, "groundContact": 1, "intensity": 1,
            "flipHorizontal": False, "canvasPadding": 32, "outputSize": OUTPUT_SIZE,
            "lightweightPreview": True}


def pack_clip(path, clip, count, fps, loop, directory):
    source_bytes = []
    frames = []
    boxes = []
    for i in range(1, count + 1):
        frame_path = path / f"sheet-{i}.png"
        raw = frame_path.read_bytes()
        source_bytes.append(raw)
        with Image.open(frame_path) as opened:
            if opened.mode != "RGBA" or opened.size != (512, 512):
                raise ValueError(f"512px RGBAではありません: {frame_path}")
            frame = opened.resize((OUTPUT_SIZE, OUTPUT_SIZE), Image.Resampling.LANCZOS)
        boxes.append(bounds(frame))
        frames.append(frame)
    extra = path / f"sheet-{count + 1}.png"
    if extra.exists():
        raise ValueError(f"余分なフレームがあります: {extra}")
    sheet = Image.new("RGBA", (OUTPUT_SIZE * count, OUTPUT_SIZE))
    for i, frame in enumerate(frames):
        sheet.paste(frame, (OUTPUT_SIZE * i, 0))
    rest = boxes[-1] if clip == "land" else boxes[0]
    contact = 4 if clip == "land" else 0
    metadata = {"schemaVersion": 1, "frameWidth": OUTPUT_SIZE, "frameHeight": OUTPUT_SIZE,
                "frameCount": count, "fps": fps, "loop": loop, "anchorX": .5, "anchorY": 1,
                "contentBounds": rest, "collisionBounds": rest,
                "sourceImage": directory + "/character.png", "preset": "standard",
                "motionAction": "move" if clip.startswith("move-") else clip,
                "clipId": clip, "motionParameters": parameters(count, fps), "partMasks": [],
                "partRegions": [], "generatedAt": "2026-11-01T00:00:00.000Z",
                "generatorVersion": "approved-sprite-pack-1",
                "rendering": {"version": 1, "sourceFacing": "right", "restBounds": rest,
                              "ground": {"x": rest["x"] + rest["width"] / 2,
                                         "y": rest["y"] + rest["height"]},
                              "contactFrame": contact}}
    return sheet, metadata, source_bytes, boxes


def catalog_read(path):
    raw = path.read_text(encoding="utf-8")
    match = re.fullmatch(r"/\* Generated by Content Studio\. Do not edit manually\. \*/\s*globalThis\.__CONTENT_STUDIO_CATALOG__ = (\{.*\});\s*", raw, re.S)
    if not match:
        raise ValueError("catalogの形式が変わりました")
    catalog = json.loads(match.group(1))
    if catalog.get("schemaVersion") != 1 or not isinstance(catalog.get("characters"), dict):
        raise ValueError("catalog schema")
    return catalog


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", nargs="*", help="asset名。省略時は18体全部")
    parser.add_argument("--others", type=Path, default=ROOT.parent / "katamon-other-characters")
    parser.add_argument("--pilot", type=Path, default=ROOT.parent / "katamon-sprite-pilot")
    parser.add_argument("--generated", type=Path, default=ROOT.parent / "all-character-sprites" / "processed")
    parser.add_argument("--check", action="store_true", help="入力と出力を検証し、書き込まない")
    args = parser.parse_args()
    selected = json.loads((args.others / "selected-folders.json").read_text(encoding="utf-8"))
    all_assets = {asset for _, asset in IDENTITIES}
    wanted = set(args.only) if args.only is not None else all_assets
    if not wanted or wanted - all_assets:
        parser.error(f"対象assetが不正です: {wanted - all_assets}")
    catalog_path = ROOT / "generated/content-studio-catalog.js"
    catalog = catalog_read(catalog_path)
    manifest_path = ROOT / "content/generated-motion-manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {"schemaVersion": 1, "characters": {}}
    if manifest.get("schemaVersion") != 1 or not isinstance(manifest.get("characters"), dict):
        raise ValueError("motion manifest schema")
    results = []
    for legacy_id, asset in IDENTITIES:
        if asset not in wanted:
            continue
        slug = next((x for x in ROOT.joinpath("tools/content-studio/src/domain/legacy-characters.ts").read_text(encoding="utf-8").splitlines()
                     if f"id: '{legacy_id}'" in x), None)
        if not slug:
            raise ValueError(f"legacy identityがありません: {legacy_id}")
        match = re.search(r"slug: '([^']+)'", slug)
        slug = match.group(1)
        sources = []
        for action, (clip, count, fps, loop) in CLIPS.items():
            path = source_dir(asset, action, selected, args.others, args.pilot, args.generated)
            sources.append((action, clip, count, fps, loop, path))
        digest = hashlib.sha256()
        digest.update(f"approved-sprite-pack-1/{OUTPUT_SIZE}".encode())
        packed = []
        for action, clip, count, fps, loop, path in sources:
            sheet, meta, raw, boxes = pack_clip(path, clip, count, fps, loop, "placeholder")
            digest.update(clip.encode())
            for item in raw:
                digest.update(len(item).to_bytes(8, "big"))
                digest.update(item)
            packed.append((clip, sheet, meta, boxes))
        digest.update((ROOT / f"assets/characters/master/{asset}.png").read_bytes())
        directory = f"assets/content-studio/{slug}/{digest.hexdigest()[:12]}"
        motion_sheets = {}
        motion_metadata = {}
        for clip, sheet, meta, boxes in packed:
            meta["sourceImage"] = directory + "/character.png"
            motion_sheets[clip] = directory + "/" + clip + ".png"
            motion_metadata[clip] = directory + "/" + clip + ".json"
            if clip == "land" and boxes[4]["y"] + boxes[4]["height"] < boxes[-1]["y"] + boxes[-1]["height"] - 32:
                raise ValueError(f"{asset}: 着地5コマ目の接地姿勢を確認してください")
            if args.check:
                target = ROOT / directory
                saved_meta = json.loads((target / f"{clip}.json").read_text(encoding="utf-8"))
                if saved_meta != meta:
                    raise ValueError(f"{asset}/{clip}: metadataが入力と一致しません")
                with Image.open(target / f"{clip}.png") as saved:
                    if saved.mode != "RGBA" or saved.size != sheet.size or ImageChops.difference(saved, sheet).getbbox(alpha_only=False):
                        raise ValueError(f"{asset}/{clip}: sprite PNGが入力と一致しません")
                if (target / f"{clip}.png").stat().st_size > 6 * 1024 * 1024:
                    raise ValueError(f"{asset}/{clip}: 6 MiB超過")
                continue
            target = ROOT / directory
            target.mkdir(parents=True, exist_ok=True)
            sheet.save(target / f"{clip}.png", optimize=True)
            if (target / f"{clip}.png").stat().st_size > 6 * 1024 * 1024:
                raise ValueError(f"{asset}/{clip}: 6 MiB超過")
            (target / f"{clip}.json").write_text(json.dumps(meta, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n", encoding="utf-8")
        if not args.check:
            (ROOT / directory / "character.png").write_bytes((ROOT / f"assets/characters/master/{asset}.png").read_bytes())
        elif (ROOT / directory / "character.png").read_bytes() != (ROOT / f"assets/characters/master/{asset}.png").read_bytes():
            raise ValueError(f"{asset}: character.pngが原画と一致しません")
        old = catalog["characters"].get(legacy_id, {})
        if old and old.get("legacyTargetId") not in (None, legacy_id):
            raise ValueError(f"catalog衝突: {legacy_id}")
        catalog["characters"][legacy_id] = {**old, "key": legacy_id, "legacyTargetId": legacy_id,
                                              "motionSheets": motion_sheets, "motionMetadata": motion_metadata}
        manifest["characters"][legacy_id] = {"asset": asset, "slug": slug, "motionSheets": motion_sheets,
                                               "motionMetadata": motion_metadata}
        results.append((asset, directory))
    catalog["order"] = list(dict.fromkeys([*catalog.get("order", []), *[legacy for legacy, asset in IDENTITIES if asset in wanted]]))
    output = "/* Generated by Content Studio. Do not edit manually. */\nglobalThis.__CONTENT_STUDIO_CATALOG__ = " + json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True) + ";\n"
    if args.check:
        if catalog_read(catalog_path) != catalog:
            raise ValueError("catalogがpack結果と一致しません")
        if json.loads(manifest_path.read_text(encoding="utf-8")) != manifest:
            raise ValueError("motion manifestがpack結果と一致しません")
    else:
        catalog_path.write_bytes(output.encode("utf-8"))
        manifest_path.parent.mkdir(parents=True, exist_ok=True)
        manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    for asset, directory in results:
        print(f"{asset}: {directory}")


if __name__ == "__main__":
    main()
