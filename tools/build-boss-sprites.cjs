// Deterministic atlas assembly only. Poses are drawn by ChatGPT, never warped here.
// NODE_PATH must contain sharp (or install it in your development environment).
const sharp = require('sharp');
const fs = require('node:fs/promises');
const path = require('node:path');
const root = path.join(__dirname, '..');
const cell = 640, anchor = [220, 440];
const specs = [
  { id:'fortress', file:'fortress-idle-source.png', rows:[0,444,887], cols:[0,446,886,1327,1774],
    body:[222,400], reference:[.5,.95], points:{twinCannon:[75,173],mainCannon:[184,135],frontArmor:[65,304],missilePod:[378,228],core:[306,300]} },
  { id:'fortressPhase2', file:'fortress-phase2-idle-source.png', rows:[0,444,887], cols:[0,444,886,1331,1774],
    body:[222,380], reference:[.5,.95], points:{twinCannon:[72,161],mainCannon:[180,124],frontArmor:[65,286],missilePod:[363,180],core:[307,279]} },
  { id:'volteris', file:'volteris-idle-source.png', rows:[0,440,940,1360,1774], cols:[0,443,887], reference:[.25,.64],
    // Measured chest anchors, and crystal sites in the generated source, per frame.
    bodies:[[127,322],[572,323],[128,787],[574,786],[128,1231],[574,1229],[128,1661],[574,1658]],
    sites:[
      [[91,227],[156,143],[244,178],[406,317]],
      [[537,220],[609,120],[693,123],[851,316]],
      [[88,689],[169,479],[305,472],[405,788]],
      [[535,684],[599,586],[696,580],[851,784]],
      [[89,1133],[83,1094],[237,1160],[406,1218]],
      [[536,1128],[589,1005],[698,1045],[850,1220]],
      [[89,1565],[170,1418],[267,1480],[405,1630]],
      [[535,1563],[514,1507],[663,1520],[851,1645]]
    ] },
];
(async()=>{
  const data = {}, qa = [];
  for(const spec of specs){
    const source=path.join(root,'assets/bosses/master/spritesheets',spec.file);
    const {data:rgba,info}=await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true});
    const composites=[], frames=[];
    for(let row=0;row<spec.rows.length-1;row++)for(let col=0;col<spec.cols.length-1;col++){
      const n=frames.length, left=spec.cols[col], top=spec.rows[row];
      const width=spec.cols[col+1]-left,height=spec.rows[row+1]-top;
      let bottom=0;
      for(let y=top;y<top+height;y++)for(let x=left;x<left+width;x++)if(rgba[(y*info.width+x)*4+3]>32)bottom=Math.max(bottom,y-top+1);
      const body=spec.bodies?spec.bodies[n].map((v,i)=>v-(i?top:left)):[spec.body[0],bottom];
      const dx=Math.round(anchor[0]-body[0]),dy=Math.round(anchor[1]-body[1]);
      // Keep complete source rectangles and all alpha; no edge erasure, trim or resizing.
      // For fortress the anchor's x is shifted to center the wider hull in its cell.
      const ax=spec.bodies?dx:dx+100;
      if(ax<0||dy<0||ax+width>cell||dy+height>cell)throw Error('frame exceeds cell: '+spec.id+' '+n);
      const input=await sharp(source).extract({left,top,width,height}).png().toBuffer();
      composites.push({input,left:(n%4)*cell+ax,top:Math.floor(n/4)*cell+dy});
      const points={};
      if(spec.sites){
        ['thunderHorn','skyWing','galeWing','tailCrystal'].forEach((id,i)=>{
          points[id]=[spec.sites[n][i][0]-left+ax,spec.sites[n][i][1]-top+dy];
        });
        points.core=[anchor[0],anchor[1]];
      }else{
        const offset=bottom-spec.body[1];
        for(const [id,p]of Object.entries(spec.points))points[id]=[p[0]+ax,p[1]+offset+dy];
      }
      frames.push({points});
      qa.push({id:spec.id,frame:n,source:{left,top,width,height},translation:[ax,dy],anchor:spec.bodies?anchor:[320,440]});
    }
    const name=spec.id==='fortressPhase2'?'fortress-phase2-idle-atlas':spec.id+'-idle-atlas';
    await sharp({create:{width:cell*4,height:cell*2,channels:4,background:{r:0,g:0,b:0,alpha:0}}})
      .composite(composites).webp({quality:80,alphaQuality:100}).toFile(path.join(root,'assets/bosses/runtime',name+'.webp'));
    data[spec.id]={path:'assets/bosses/runtime/'+name+'.webp',cell,columns:4,count:8,fps:7,
      sourceWidth:444,anchor:spec.bodies?anchor:[320,440],reference:spec.reference,frames};
  }
  await fs.writeFile(path.join(root,'shared/coop-boss-sprite-data.js'),
    '// Generated by tools/build-boss-sprites.cjs; presentation metadata only.\n'+
    '(function(root){const data='+JSON.stringify(data)+'; if(typeof module===\'object\'&&module.exports)module.exports=data; if(root)root.KatamonBossSpriteData=data;})(typeof globalThis!==\'undefined\'?globalThis:this);\n');
  await fs.writeFile(path.join(root,'assets/bosses/master/spritesheets/assembly.json'),JSON.stringify(qa,null,2)+'\n');
  console.log('Built 3 atlases, 8 frames each, translation only; source rectangles preserved.');
})().catch(e=>{console.error(e);process.exitCode=1;});
